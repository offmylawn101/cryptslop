const CHARS = Object.keys(G);
const CW = 6, CH = 8; // cell size incl. 1px spacing
const atlases = new Map();

function atlas(color) {
  let a = atlases.get(color);
  if (a) return a;
  const c = document.createElement('canvas');
  c.width = CHARS.length * CW; c.height = CH;
  const g = c.getContext('2d');
  g.fillStyle = color;
  CHARS.forEach((ch, n) => {
    const rows = G[ch];
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (rows[y][x] === '#') g.fillRect(n * CW + x, y, 1, 1);
  });
  a = c; atlases.set(color, a);
  return a;
}

const indexOf = new Map(CHARS.map((c, i) => [c, i]));

export function textWidth(str, scale = 1) { return str.length * CW * scale - scale; }

// align: 'left' | 'center' | 'right'. shadow draws a 1px dark drop shadow.
export function drawText(ctx, str, x, y, color = '#fff', scale = 1, align = 'left', shadow = true) {
  str = String(str).toUpperCase();
  const w = textWidth(str, scale);
  let sx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  y = Math.round(y);
  if (shadow) drawRaw(ctx, str, sx + scale, y + scale, '#000', scale);
  drawRaw(ctx, str, sx, y, color, scale);
  return w;
}

function drawRaw(ctx, str, x, y, color, scale) {
  const a = atlas(color);
  for (let i = 0; i < str.length; i++) {
    let n = indexOf.get(str[i]);
    if (n === undefined) n = indexOf.get('?');
    ctx.drawImage(a, n * CW, 0, CW - 1, 7, x + i * CW * scale, y, (CW - 1) * scale, 7 * scale);
  }
}

